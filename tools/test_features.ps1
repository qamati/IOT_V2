$ErrorActionPreference = "Stop"

Write-Host "=== 1. Login as Tenant Admin ==="
$loginResp = Invoke-RestMethod -Uri "http://localhost:8080/api/v1/auth/login" -Method Post -ContentType "application/json" -Body '{"email":"tenant@example.com","password":"Secret123!"}'
$token = $loginResp.token
$headers = @{ "Authorization" = "Bearer $token" }
Write-Host "Logged in successfully. User: $($loginResp.user.email) Tenant: $($loginResp.user.tenant_id)"

Write-Host "`n=== 2. List Devices ==="
$devicesResp = Invoke-RestMethod -Uri "http://localhost:8080/api/v1/devices" -Headers $headers
$dev = $devicesResp.data[0]
Write-Host "Discovered seeded device: $($dev.name) (ID: $($dev.id))"

Write-Host "`n=== 3. Query Device Activity ==="
$activity = Invoke-RestMethod -Uri "http://localhost:8080/api/v1/devices/$($dev.id)/activity" -Headers $headers
Write-Host "Device Activity: active = $($activity.active), last_activity = $($activity.last_activity_time)"

Write-Host "`n=== 4. Query Scoped Attributes ==="
$attrs = Invoke-RestMethod -Uri "http://localhost:8080/api/v1/plugins/telemetry/DEVICE/$($dev.id)/values/attributes" -Headers $headers
Write-Host "Discovered $($attrs.Count) attributes:"
foreach ($a in $attrs) {
    Write-Host "  [$($a.scope)] $($a.key) = $($a.value)"
}

Write-Host "`n=== 5. Trigger Rule Engine Alarm (High Temperature 49.2°C) ==="
Invoke-RestMethod -Uri "http://localhost:8080/api/v1/DEV_ALPHA_TOKEN_123/telemetry" -Method Post -ContentType "application/json" -Body '{"temperature": 49.2, "humidity": 38.5}'
Start-Sleep -Milliseconds 400

Write-Host "`n=== 6. Query Alarms Generated by Rule Engine ==="
$alarmsResp = Invoke-RestMethod -Uri "http://localhost:8080/api/v1/alarms" -Headers $headers
Write-Host "Total Alarms: $($alarmsResp.total)"
if ($alarmsResp.total -gt 0) {
    $alarm = $alarmsResp.data[0]
    Write-Host "Alarm ID: $($alarm.id)"
    Write-Host "Type: $($alarm.type)"
    Write-Host "Severity: $($alarm.severity)"
    Write-Host "Status: $($alarm.status)"

    Write-Host "`n=== 7. Acknowledge Alarm ==="
    $ackResp = Invoke-RestMethod -Uri "http://localhost:8080/api/v1/alarms/$($alarm.id)/ack" -Method Post -Headers $headers
    Write-Host "Updated Alarm Status: $($ackResp.status) (AckTs: $($ackResp.ack_ts))"

    Write-Host "`n=== 8. Clear Alarm ==="
    $clearResp = Invoke-RestMethod -Uri "http://localhost:8080/api/v1/alarms/$($alarm.id)/clear" -Method Post -Headers $headers
    Write-Host "Updated Alarm Status: $($clearResp.status) (ClearTs: $($clearResp.clear_ts))"
}

Write-Host "`n>>> ALL STAGE 1-5 FEATURES VERIFIED SUCCESSFULLY! <<<"
